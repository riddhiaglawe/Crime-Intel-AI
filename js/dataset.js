// Helper to expand raw CSV records into complete CrimeIntel AI case objects with evidence & suspects
export function buildFormattedDataset() {
  const suspectNamePool = [
    "Rajesh 'Raju' Verma", "Sameer 'Monu' Shaikh", "Vikas 'Vicky' Patil", 
    "Sunil 'Guddu' Deshmukh", "Anil 'Bablu' Meshram", "Rohan 'Rocky' Shinde",
    "Imran 'Chhotu' Khan", "Deepak 'Pintu' Gaikwad", "Manoj 'Kalia' Tiwari",
    "Sanjay 'Sanju' Kapse", "Nitin 'Bittu' Wankhede", "Gaurav 'Monty' Bhende",
    "Pravin 'Bhaiya' Kale", "Amit 'Sonu' Rathod", "Kunal 'Dada' Thakre"
  ];

  return RAW_NAGPUR_CASES.map((raw, idx) => {
    // Parse Evidence Items
    const evItems = [];
    if (raw.evidenceSummary && raw.evidenceSummary !== "No evidence logged yet") {
      const parts = raw.evidenceSummary.split(";").map(s => s.trim()).filter(Boolean);
      parts.forEach((pText, eIdx) => {
        let evType = "forensic";
        const lower = pText.toLowerCase();
        if (lower.includes("witness") || lower.includes("victim") || lower.includes("eyewitness") || lower.includes("neighbour")) {
          evType = "witness";
        } else if (lower.includes("cctv") || lower.includes("camera") || lower.includes("ip") || lower.includes("transaction") || lower.includes("chat") || lower.includes("email") || lower.includes("record") || lower.includes("screenshot") || lower.includes("login")) {
          evType = "digital";
        } else if (lower.includes("item") || lower.includes("object") || lower.includes("chain") || lower.includes("vehicle") || lower.includes("property")) {
          evType = "physical";
        }

        evItems.push({
          id: `e_${raw.num.toLowerCase()}_${eIdx + 1}`,
          type: evType,
          text: `${pText} logged for incident at ${raw.location}.`,
          location: raw.location,
          time: `${raw.opened} 10:${String(15 + eIdx * 12).padStart(2, '0')}`,
          tags: raw.keywords.slice(0, 3).concat([evType]),
          loggedAt: `${raw.opened}T10:${String(15 + eIdx * 12).padStart(2, '0')}:00`
        });
      });
    }

    // Generate Suspects matching suspectCount
    const suspects = [];
    for (let s = 0; s < raw.suspectCount; s++) {
      const nameIndex = (idx * 3 + s) % suspectNamePool.length;
      const sName = suspectNamePool[nameIndex];
      const sId = `s_${raw.num.toLowerCase()}_${s + 1}`;
      
      const sTags = [
        raw.keywords[0] || "suspect",
        raw.location.toLowerCase(),
        raw.crimeType.toLowerCase()
      ];
      if (idx % 2 === 0) sTags.push("grey vehicle");
      if (idx % 3 === 0) sTags.push("night operative");

      suspects.push({
        id: sId,
        name: sName,
        alias: `Person of interest linked to ${raw.crimeType} in ${raw.location}`,
        tags: sTags,
        addedAt: `${raw.opened}T14:30:00`,
        score: (idx % 4 === 0) ? 82 : (idx % 3 === 0) ? 65 : (idx % 2 === 0) ? 45 : null,
        matches: [],
        crossCase: []
      });
    }

    return {
      id: raw.id.toLowerCase(),
      num: raw.num,
      title: raw.title,
      crimeType: raw.crimeType,
      description: raw.description,
      location: raw.location,
      opened: raw.opened,
      keywords: raw.keywords,
      status: raw.status === "closed" ? "closed" : raw.status === "critical" ? "critical" : "open",
      priority: raw.priority,
      firText: raw.firText,
      evidence: evItems,
      suspects: suspects
    };
  });
}
